internal fun LocalDate.toChineseLunarDate(): ChineseLunarDate? {
    var remaining = firstLunarNewYear.daysUntil(this)
    if (remaining < 0) return null
    for (year in lunarYears) {
        val leapMonth = year and 0xf
        val longMonths = year ushr 4
        val monthCount = if (leapMonth == 0) 12 else 13
        val yearLength = 29 * monthCount + longMonths.countOneBits()
        if (remaining >= yearLength) {
            remaining -= yearLength
            continue
        }
        for (slot in 1..monthCount) {
            val monthLength = 29 + ((longMonths ushr (slot - 1)) and 1)
            if (remaining < monthLength) {
                val afterRegularMonth = leapMonth != 0 && slot > leapMonth
                val month = if (afterRegularMonth) slot - 1 else slot
                return ChineseLunarDate(month, remaining + 1, afterRegularMonth && month == leapMonth)
            }
            remaining -= monthLength
        }
    }
    return null
}
